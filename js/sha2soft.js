const rotr64 = (x, n) => (((x >> n) | (x << (64n - n))) & M64);

export function sha512Soft(message) {
  let H = [
    0x6a09e667f3bcc908n, 0xbb67ae8584caa73bn, 0x3c6ef372fe94f82bn, 0xa54ff53a5f1d36f1n,
    0x510e527fade682d1n, 0x9b05688c2b3e6c1fn, 0x1f83d9abfb41bd6bn, 0x5be0cd19137e2179n,
  ];

  const bitLen = BigInt(message.length) * 8n;
  // ceil((len + 1-byte-0x80 + 16-byte-length) / 128) * 128
  const paddedLen = (((message.length + 1 + 16 + 127) >> 7) << 7);
  const buf = new Uint8Array(paddedLen);
  buf.set(message);
  buf[message.length] = 0x80;
  const dv = new DataView(buf.buffer);
  dv.setBigUint64(paddedLen - 8, bitLen & M64, false);

  const w = new Array(80);
  for (let block = 0; block < paddedLen; block += 128) {
    for (let i = 0; i < 16; i++) w[i] = dv.getBigUint64(block + i * 8, false);
    for (let i = 16; i < 80; i++) {
      const s0 = rotr64(w[i - 15], 1n) ^ rotr64(w[i - 15], 8n) ^ (w[i - 15] >> 7n);
      const s1 = rotr64(w[i - 2], 19n) ^ rotr64(w[i - 2], 61n) ^ (w[i - 2] >> 6n);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) & M64;
    }
    let [a, b, c, d, e, f, g, h] = H;
    for (let i = 0; i < 80; i++) {
      const S1 = rotr64(e, 14n) ^ rotr64(e, 18n) ^ rotr64(e, 41n);
      const ch = (e & f) ^ (~e & g);
      const t1 = (h + S1 + ch + K512[i] + w[i]) & M64;
      const S0 = rotr64(a, 28n) ^ rotr64(a, 34n) ^ rotr64(a, 39n);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) & M64;
      h = g; g = f; f = e; e = (d + t1) & M64;
      d = c; c = b; b = a; a = (t1 + t2) & M64;
    }
    H = [
      (H[0] + a) & M64, (H[1] + b) & M64, (H[2] + c) & M64, (H[3] + d) & M64,
      (H[4] + e) & M64, (H[5] + f) & M64, (H[6] + g) & M64, (H[7] + h) & M64,
    ];
  }

  const out = new Uint8Array(64);
  const odv = new DataView(out.buffer);
  for (let i = 0; i < 8; i++) odv.setBigUint64(i * 8, H[i], false);
  return out;
}

// ---------------------------------------------------------------------------
// HMAC-SHA512 (RFC 2104)
// ---------------------------------------------------------------------------

export function hmacSha512Soft(key, data) {
  const BLOCK = 128;
  let k = key.length > BLOCK ? sha512Soft(key) : key;
  if (k.length < BLOCK) {
    const padded = new Uint8Array(BLOCK);
    padded.set(k);
    k = padded;
  }
  const ipad = new Uint8Array(BLOCK);
  const opad = new Uint8Array(BLOCK);
  for (let i = 0; i < BLOCK; i++) { ipad[i] = k[i] ^ 0x36; opad[i] = k[i] ^ 0x5c; }
  const inner = new Uint8Array(BLOCK + data.length);
  inner.set(ipad); inner.set(data, BLOCK);
  const innerHash = sha512Soft(inner);
  const outer = new Uint8Array(BLOCK + 64);
  outer.set(opad); outer.set(innerHash, BLOCK);
  return sha512Soft(outer);
}
